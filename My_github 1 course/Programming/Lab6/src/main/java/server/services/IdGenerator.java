package server.services;

/**
 * Интерфейс для генерации уникальных идентификаторов.
 * Используется для отделения логики генерации id от логики создания объектов.
 * Позволяет использовать различные стратегии генерации идентификаторов
 * (например, последовательную, случайную и т.д.).
 *
 * @author Эльдар
 * @version 1.0
 */
public interface IdGenerator {
    /**
     * Генерирует следующий уникальный идентификатор.
     *
     * @return новый уникальный id
     */
    long nextId();
    /**
     * Устанавливает текущее максимальное значение id.
     * Используется при загрузке данных из файла,
     * чтобы избежать конфликтов идентификаторов.
     *
     * @param currentMaxId максимальный существующий id в коллекции
     */
    void setCurrentMaxId(long currentMaxId);
}
